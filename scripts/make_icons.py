#!/usr/bin/env python3
"""Draws the launcher icon, a budget pie in three slices, as both:

- the adaptive icon (res/drawable/ic_launcher_foreground.xml + res/mipmap-anydpi-v26/ic_launcher.xml),
  which phones use, and
- PNGs (res/mipmap-*/ic_launcher.png), which F-Droid needs to show an icon.

    python3 scripts/make_icons.py
"""
import math
import os

import cairo

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
BACKGROUND = "#0E3B43"
# (start, end) in degrees clockwise from 12 o'clock, colour.
SLICES = [(0, 150, "#34D399"), (150, 250, "#FBBF24"), (250, 360, "#60A5FA")]
CX = CY = 54.0  # adaptive icon viewport is 108 x 108; the launcher shows the middle 72
RADIUS = 22.0
GAP = 2.4  # width of the background-coloured lines between slices
SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def point(deg):
    a = math.radians(deg - 90)
    return CX + RADIUS * math.cos(a), CY + RADIUS * math.sin(a)


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def vector_xml():
    paths = []
    for start, end, colour in SLICES:
        x1, y1 = point(start)
        x2, y2 = point(end)
        large = 1 if end - start > 180 else 0
        paths.append(
            f'    <path\n        android:fillColor="{colour}"\n'
            f'        android:pathData="M{CX:g},{CY:g} L{x1:.3f},{y1:.3f} '
            f'A{RADIUS:g},{RADIUS:g} 0 {large} 1 {x2:.3f},{y2:.3f} Z" />'
        )
    for start, _, _ in SLICES:
        x, y = point(start)
        paths.append(
            f'    <path\n        android:strokeColor="{BACKGROUND}"\n        android:strokeWidth="{GAP:g}"\n'
            f'        android:pathData="M{CX:g},{CY:g} L{x:.3f},{y:.3f}" />'
        )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/make_icons.py: a budget pie in three slices. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""

COLORS = f"""<resources>
    <color name="icon_background">{BACKGROUND}</color>
</resources>
"""


def png(size):
    surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, size, size)
    ctx = cairo.Context(surface)
    r = size * 0.22
    ctx.new_sub_path()
    ctx.arc(size - r, r, r, -math.pi / 2, 0)
    ctx.arc(size - r, size - r, r, 0, math.pi / 2)
    ctx.arc(r, size - r, r, math.pi / 2, math.pi)
    ctx.arc(r, r, r, math.pi, 3 * math.pi / 2)
    ctx.close_path()
    ctx.set_source_rgb(*rgb(BACKGROUND))
    ctx.fill()
    # Show the middle 72 of the 108 viewport, like a launcher mask does.
    ctx.scale(size / 72.0, size / 72.0)
    ctx.translate(-18, -18)
    for start, end, colour in SLICES:
        ctx.move_to(CX, CY)
        ctx.arc(CX, CY, RADIUS, math.radians(start - 90), math.radians(end - 90))
        ctx.close_path()
        ctx.set_source_rgb(*rgb(colour))
        ctx.fill()
    ctx.set_line_width(GAP)
    ctx.set_source_rgb(*rgb(BACKGROUND))
    for start, _, _ in SLICES:
        ctx.move_to(CX, CY)
        ctx.line_to(*point(start))
        ctx.stroke()
    return surface


def write(rel, text):
    path = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    print(rel)


write("drawable/ic_launcher_foreground.xml", vector_xml())
write("mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE)
write("values/colors.xml", COLORS)
for density, px in SIZES.items():
    os.makedirs(os.path.join(RES, f"mipmap-{density}"), exist_ok=True)
    png(px).write_to_png(os.path.join(RES, f"mipmap-{density}", "ic_launcher.png"))
    print(f"mipmap-{density}/ic_launcher.png")
